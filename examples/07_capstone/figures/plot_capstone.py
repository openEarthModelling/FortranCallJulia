# ---------------------------------------------------------------- fig 6 ----
def fig6(bridge, native):
    t_ms = bridge[:, 0] * 1e3
    fig, (axO, axR) = plt.subplots(2, 1, figsize=(W_SINGLE, 100 * MM),
                                   sharex=True)

    # (a) overlay: computed through the bridge (blue solid) vs the native
    # Julia reference (red dashed on top) -- the family's coincidence idiom.
    # Under the pinned runtime the two runs are bit-identical (panel b), so
    # this is literally the same trajectory drawn twice.
    style_axis(axO)
    axO.plot(t_ms, bridge[:, 1], color=PALETTE["blue_main"], lw=1.4,
             label="bridge (Fortran extraction)", zorder=3)
    axO.plot(t_ms, native[:, 1], color=PALETTE["red_strong"], lw=1.0,
             ls=(0, (3, 2)), label="native (direct Julia)", zorder=4)
    axO.set_ylabel("T (K)", fontsize=7)
    axO.legend(fontsize=5.5, loc="lower right", handlelength=1.6,
               borderaxespad=0.3)
    add_panel_label(axO, "a")

    # (b) pointwise relative residuals over T + the four species,
    # conditioning-floored denominator (R_DEN_FLOOR).  With the baseline
    # generated under the pinned runtime (the same libjulia the bridge
    # embeds) every value is bit-identical: r = 0 exactly, all points fall
    # below the 1e-12 display floor and no curve enters the panel -- the
    # emptiness IS the result, framed by the display floor and the 1e-8
    # gate.  If a drifted runtime pair ever lands here (guard bypassed),
    # the curves reappear (only r >= 1e-12 is drawn) and the annotation
    # reports the measured maximum instead.
    style_axis(axR)
    series = [("T", PALETTE["blue_main"], bridge[:, 1], native[:, 1])]
    series += [(sp, SPECIES_COLOR[sp], bridge[:, 2 + k], native[:, 2 + k])
               for k, sp in enumerate(SPECIES_COLOR)]
    n_floor = 0
    n_zero = 0
    r_max = 0.0
    for name, color, vb, vn in series:
        r = np.abs(vb - vn) / np.maximum(np.abs(vn), R_DEN_FLOOR)
        n_zero += int(np.sum(vb == vn))
        n_floor += int(np.sum(r < 1e-12))
        r_max = max(r_max, r.max())
        # sub-floor points masked (a log axis cannot show them; unmasked
        # vertices leave the axes box in the PDF path geometry)
        m = r >= 1e-12
        if m.any():
            axR.plot(t_ms[m], r[m], color=color, lw=0.7, label=name,
                     zorder=3)
    axR.axhline(GRI_REL_TOL, color=PALETTE["red_strong"], lw=1.0,
                ls=(0, (3, 2)), zorder=4)
    axR.axhline(1e-12, color=PALETTE["neutral_mid"], lw=0.7,
                ls=(0, (1, 2)), zorder=2)
    # right-side labels stacked between the two reference lines: the panel
    # is empty in the pinned case, so the only collision candidates are
    # these two texts and the top-left annotation
    axR.text(t_ms[-1] * 0.98, GRI_REL_TOL * 1.9, "10⁻⁸ acceptance gate",
             ha="right", va="bottom", fontsize=5.5,
             color=PALETTE["red_strong"])
    axR.text(t_ms[-1] * 0.98, 1e-12 * 2.2, "display floor 10⁻¹²",
             ha="right", va="bottom", fontsize=5.5,
             color=PALETTE["neutral_mid"])
    axR.set_yscale("log")
    # frame for the empty-by-result panel (drifted case: peak headroom x10)
    axR.set_ylim(3e-13, max(1e-5, r_max * 10))
    pow10_ticks(axR, [-12, -10, -8, -6])
    if r_max < 1e-12:
        # pinned-runtime normal case: the four acceptance scalars are
        # bit-equal and every series residual sits below the display floor
        # (measured max ~8e-13, trace-species ULP-level reorderings) -- no
        # curve enters the panel and that emptiness is the result
        axR.text(0.03, 0.95,
                 f"same pinned runtime: max rel. residual {r_max:.0e}\n"
                 f"({n_zero}/{5 * len(t_ms)} values bit-identical) --\n"
                 "all points below the display floor",
                 transform=axR.transAxes, ha="left", va="top", fontsize=5.5,
                 color=PALETTE["neutral_black"], linespacing=1.3)
    else:
        # curves visible above the floor: not the acceptance pair the
        # protocol defines (pinned runtime) -- say so, with the number
        axR.text(0.03, 0.95,
                 f"drifted pair: max rel. residual {r_max:.1e}\n"
                 "(baseline not from the pinned runtime -- see the\n"
                 "run_gri_native.jl version guard)",
                 transform=axR.transAxes, ha="left", va="top", fontsize=5.5,
                 color=PALETTE["neutral_black"], linespacing=1.3)
    axR.set_xlabel("t (ms)", fontsize=7)
    axR.set_ylabel("rel. residual", fontsize=7)
    add_panel_label(axR, "b")

    finalize(fig, "fig6_bridge_vs_native")
    print(
        "  panel audit: a T overlay (blue=bridge, red dash=native on top) |\n"
        f"  b residuals T+4 species, denominator floored at {R_DEN_FLOOR:g};\n"
        f"  pinned-runtime pair: {n_zero}/{5 * len(t_ms)} values\n"
        f"  bit-identical, max rel. residual {r_max:.1e} (all below the\n"
        f"  1e-12 display floor; {n_floor} points) -- an empty residual\n"
        "  panel is the result, not a failure."
    )


